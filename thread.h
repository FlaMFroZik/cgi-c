/*
 * thread.h — пул рабочих потоков.
 *
 * Работа сервера разделена между потоками так:
 *
 *   главный поток (socket.c)   принимает соединения и кладёт сокеты
 *                              клиентов в очередь пула;
 *   рабочие потоки (thread.c)  забирают сокеты из очереди и для каждого
 *                              вызывают функцию-обработчик — её адрес
 *                              передаётся в пул указателем thread_task_t.
 *
 * Пул ничего не знает ни о HTTP, ни о CGI: он просто выполняет переданную
 * функцию в одном из своих потоков.
 */
#ifndef CGI_THREAD_H
#define CGI_THREAD_H

#include <stddef.h> /* size_t */

/*
 * Функция-обработчик: рабочий поток вызывает её для каждого соединения.
 *   client — сокет клиента (обработчик обязан его закрыть);
 *   arg    — указатель, переданный в thread_pool_create().
 */
typedef void (*thread_task_t)(int client, void *arg);

/* Пул потоков. Устройство скрыто в thread.c. */
typedef struct thread_pool thread_pool_t;

/*
 * Запустить threads рабочих потоков и очередь на queue_size соединений.
 * Каждый поток выполняет task(client, arg) для очередного соединения.
 * Возвращает пул или NULL при ошибке.
 */
thread_pool_t *thread_pool_create(size_t threads, size_t queue_size,
                                  thread_task_t task, void *arg);

/*
 * Положить сокет клиента в очередь. Свободный поток заберёт его сразу.
 * Возвращает 0 или -1, если очередь заполнена (или пул останавливается) —
 * тогда сокет остаётся у вызывающего.
 */
int thread_pool_push(thread_pool_t *pool, int client);

/*
 * Остановить пул: потоки дообслуживают всё, что уже стоит в очереди,
 * и завершаются. Функция ждёт их завершения и освобождает память.
 */
void thread_pool_destroy(thread_pool_t *pool);

#endif /* CGI_THREAD_H */
