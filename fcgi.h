/*
 * fcgi.h — FastCGI-приложение как библиотека для вашего main.c.
 *
 * Приложение здесь — не отдельная программа и не динамическая
 * библиотека (.so), которую пришлось бы загружать во время работы.
 * Это обычный код, который компонуется с вашей программой на этапе
 * сборки: Makefile собирает его в статическую библиотеку
 * libfcgi-server.a, а вы добавляете её в свою программу одной
 * командой:
 *
 *     cc -o myapp main.c libfcgi-server.a -pthread
 *
 * Всё, что нужно сделать в main.c:
 *
 *     int cgi_main(char *root, fcgi_env_t *env, char *data, size_t size,
 *                  fcgi_stream_t *out)
 *     {
 *         ...обработать запрос, написать ответ в out...
 *     }
 *
 *     int main(int argc, char **argv)
 *     {
 *         return fcgi_run(cgi_main, argc, argv);
 *     }
 *
 * Адрес функции передаётся в fcgi_run() обычным указателем —
 * никаких dlopen()/dlsym(): соответствие типов проверяет компилятор.
 *
 * С протоколом FastCGI ваше приложение говорит библиотека, а HTTP
 * разбирает веб-сервер перед ней (nginx, Apache, lighttpd, Caddy).
 */
#ifndef FCGI_SERVER_H
#define FCGI_SERVER_H

#include <stddef.h> /* size_t */

/* Размер буфера root: 256 символов, включая завершающий '\0'
 * (то есть сам путь — не длиннее 255 символов). */
#define FCGI_ROOT_SIZE 256

/* Значения по умолчанию для ключей командной строки (см. fcgi_run()). */
#define FCGI_DEFAULT_ADDRESS "127.0.0.1" /* -a: только этот компьютер */
#define FCGI_DEFAULT_PORT    "9000"      /* -p */
#define FCGI_DEFAULT_ROOT    "."         /* -r: текущая папка */
#define FCGI_DEFAULT_THREADS 16          /* -t */
#define FCGI_DEFAULT_MAX     (1024 * 1024) /* -m: макс. размер тела, байт */
#define FCGI_DEFAULT_TIMEOUT 10          /* -T: таймаут, секунд */
#define FCGI_QUEUE_SIZE      256         /* очередь соединений в пуле */

/* ======================================================================== */
/* Окружение запроса (записи FCGI_PARAMS)                                  */
/* ======================================================================== */

/* Карта «имя → значение»: то, что веб-сервер прислал в PARAMS.
 * Тип непрозрачный — работа только через функции ниже. */
typedef struct fcgi_env fcgi_env_t;

/* Пустая карта. Вернёт NULL при нехватке памяти. */
fcgi_env_t *fcgi_env_create(void);

/*
 * Добавить переменную. Имя и значение копируются, их можно не
 * хранить. При повторном имени старое значение заменяется.
 * Возвращает 0 или -1 при нехватке памяти.
 */
int fcgi_env_add(fcgi_env_t *env, const char *name, const char *value);

/* Значение переменной или NULL, если её нет. */
const char *fcgi_env_get(const fcgi_env_t *env, const char *name);

/* Освободить карту. */
void fcgi_env_free(fcgi_env_t *env);

/* ======================================================================== */
/* Поток ответа (записи FCGI_STDOUT / FCGI_STDERR)                          */
/* ======================================================================== */

/*
 * Поток, в который приложение пишет ответ. Библиотека сама разрезает
 * его на записи FastCGI (по 65535 байт) и отправляет веб-серверу.
 * Поля — внутренние: не меняйте их вручную, используйте функции.
 */
typedef struct {
    int      fd;         /* сокет веб-сервера */
    int      request_id; /* номер запроса в записях */
    int      framed;     /* 1 — оборачивать в записи FastCGI,
                            0 — писать «голые» байты (режим отладки) */
    size_t   written;    /* сколько байт уже отправлено в STDOUT */
} fcgi_stream_t;

/*
 * Записать ответ (или его часть). Буфер можно не хранить — данные
 * копируются. Возвращает 0 или -1, если веб-сервер закрыл соединение.
 */
int fcgi_write(fcgi_stream_t *out, const char *buf, size_t len);

/* То же, но в поток STDERR — для отладки: записи попадут в журнал
 * веб-сервера (error_log). */
int fcgi_write_err(fcgi_stream_t *out, const char *buf, size_t len);

/* Удобная обёртка над fcgi_write() (формат — как в printf).
 * Строка пишется целиком, какой бы длинной она ни была (при
 * нехватке памяти вернёт -1). */
int fcgi_printf(fcgi_stream_t *out, const char *fmt, ...);

/* Сколько байт ответа уже отправлено через fcgi_write(). */
size_t fcgi_stream_bytes(const fcgi_stream_t *out);

/* ======================================================================== */
/* Приложение                                                               */
/* ======================================================================== */

/*
 * Тип функции-обработчика — указатель на функцию вида
 *
 *     int cgi_main(char *root, fcgi_env_t *env, char *data,
 *                  size_t size, fcgi_stream_t *out);
 *
 * Имя функции может быть любым: сервер находит её не по имени, а по
 * указателю, который вы передаёте в fcgi_run().
 *
 *   root  — буфер ровно из FCGI_ROOT_SIZE (256) символов: абсолютный
 *           путь к корневой папке (ключ -r), всегда завершён '\0'.
 *           У каждого запроса своя копия — её можно менять.
 *   env   — окружение запроса: переменные из записей PARAMS
 *           (REQUEST_METHOD, REQUEST_URI, QUERY_STRING, CONTENT_TYPE,
 *           CONTENT_LENGTH, REMOTE_ADDR, HTTP_* и т. п.). Карта живёт
 *           только во время вызова — значения, которые нужны дольше,
 *           надо скопировать.
 *   data  — тело запроса (записи STDIN), «голые» байты: ровно так,
 *           как пришло, с дописанным после последнего байта '\0', так
 *           что текст можно обрабатывать как строку. Если тела нет,
 *           data — не NULL, а указатель на пустую строку. Буфер можно
 *           менять (например, разбирать «на месте»), но нельзя
 *           освобождать и хранить после возврата.
 *   size  — сколько байт в data (без дописанного '\0'). Нужен, потому
 *           что в теле могут быть нулевые байты, а strlen() остановится
 *           на первом из них.
 *   out   — поток ответа: сюда пишет полный ответ — строку статуса
 *           («Status: 200 OK»), заголовки, пустую строку и тело
 *           (fcgi_write(), fcgi_printf()...). Закрывать ничего не надо.
 *
 * Функция вызывается одновременно из нескольких рабочих потоков,
 * поэтому она должна быть потокобезопасной (никаких глобальных
 * переменных без мьютекса) и не должна завершать процесс (exit(),
 * abort()): её падение роняет весь сервер.
 *
 * Возвращает код состояния приложения (>= 0) — он попадает в запись
 * END_REQUEST и в журнал сервера; можно вернуть 0. Отрицательное
 * значение означает «ответ не отправлен». Если к моменту возврата в
 * out не записано ни байта (неважно, что вернула функция), сервер сам
 * пошлёт «Status: 500 Internal Server Error»: пустой ответ недопустим —
 * веб-сервер принял бы его за ошибку протокола.
 */
typedef int (*fcgi_function_t)(char *root, fcgi_env_t *env,
                               char *data, size_t size, fcgi_stream_t *out);

/*
 * Запустить FastCGI-приложение с функцией app. Функция блокирующая:
 * возвращается, только когда сервер остановлен (Ctrl+C или SIGTERM),
 * поэтому обычно её результат сразу становится результатом main().
 *
 * argc и argv передавайте как есть — сервер сам разбирает ключи:
 *
 *   -p PORT   TCP-порт (по умолчанию 9000)
 *   -a ADDR   адрес для прослушивания (по умолчанию 127.0.0.1; IPv6 — ::)
 *   -s PATH   Unix-сокет вместо TCP (путь не длиннее 107 символов);
 *               если задан, -a и -p игнорируются
 *   -r ROOT   корневая папка, передаётся в приложение как root
 *               (по умолчанию ".")
 *   -t N      число рабочих потоков (по умолчанию 16)
 *   -m BYTES  максимальный размер тела запроса в байтах
 *               (по умолчанию 1 МиБ)
 *   -T SEC    таймаут: за сколько секунд веб-сервер должен прислать
 *               запрос целиком; он же — таймаут чтения и записи сокета
 *               (по умолчанию 10)
 *   -q        не печатать журнал запросов
 *   -h        показать справку (fcgi_run вернёт 0, ничего не запустив)
 *
 * Возвращает 0 при штатной остановке, 1 при ошибке запуска, 2 при
 * неверных ключах — значения подходят в качестве кода выхода вашей
 * программы.
 */
int fcgi_run(fcgi_function_t app, int argc, char **argv);

/* ======================================================================== */
/* Низкий уровень: слушающие сокеты                                         */
/*                                                                          */
/* Их использует сам fcgi_run(). Они пригодятся, если захочется написать   */
/* свой цикл работы с протоколом вместо готового (см. fcgi.c).            */
/* ======================================================================== */

/*
 * Открыть слушающий TCP-сокет на address:port (IPv4 или IPv6).
 * Возвращает дескриптор или -1 при ошибке.
 */
int socket_listen(const char *address, const char *port);

/*
 * Открыть слушающий Unix-сокет по пути path. Старый файл сокета
 * (если это действительно сокет) удаляется. Права — 0666, чтобы
 * подключиться мог веб-сервер, работающий от другого пользователя.
 * Возвращает дескриптор или -1 при ошибке.
 */
int socket_listen_unix(const char *path);

/*
 * Закрыть соединение. linger = 1 — недолго дочитываются остатки
 * входящих данных, чтобы ядро не оборвало соединение (RST) раньше,
 * чем веб-сервер прочтёт ответ.
 */
void socket_close(int fd, int linger);

#endif /* FCGI_SERVER_H */
