/*
 * socket.h — управляющий модуль сервера.
 *
 * socket.c содержит main() и связывает остальные модули:
 *
 *   1. разбирает ключи командной строки;
 *   2. импортирует CGI-функцию из библиотеки        (import.h);
 *   3. запускает пул рабочих потоков                 (thread.h);
 *   4. открывает слушающий сокет и в цикле принимает соединения,
 *      передавая каждое в пул;
 *   5. по Ctrl+C / SIGTERM корректно всё останавливает.
 *
 * Ниже — функции для работы с сокетами. Их вызывают и главный поток,
 * и рабочие потоки (через обработчик соединения в socket.c).
 */
#ifndef CGI_SOCKET_H
#define CGI_SOCKET_H

#include <stddef.h> /* size_t */

/* Значения по умолчанию (меняются ключами командной строки, см. -h). */
#define SOCKET_DEFAULT_ADDRESS "0.0.0.0"          /* -a: все сетевые интерфейсы */
#define SOCKET_DEFAULT_PORT    "8080"             /* -p */
#define SOCKET_DEFAULT_ROOT    "."                /* -r: текущая папка */
#define SOCKET_DEFAULT_LIBRARY "./example/cgi.so" /* -l */
#define SOCKET_DEFAULT_THREADS 16                 /* -t */
#define SOCKET_DEFAULT_MAX     (1024 * 1024)      /* -m: макс. размер запроса, байт */
#define SOCKET_DEFAULT_TIMEOUT 10                 /* -T: таймаут, секунд */
#define SOCKET_QUEUE_SIZE      256                /* очередь соединений в пуле */

/*
 * Открыть слушающий TCP-сокет на address:port (IPv4 или IPv6).
 * Возвращает дескриптор или -1 при ошибке.
 */
int socket_listen(const char *address, const char *port);

/*
 * Прочитать один запрос клиента целиком: заголовки до пустой строки и
 * тело длиной Content-Length. Данные НЕ разбираются и не меняются —
 * это «голые» байты из сокета; после них дописывается '\0'.
 *
 * В *data возвращается буфер (освобождает вызывающий через free(),
 * даже при ошибке), в *size — число байт в нём.
 *
 * Возвращает:
 *    0  — запрос получен полностью;
 *   >0  — HTTP-код ошибки, который надо отправить клиенту
 *         (400, 408, 411, 413, 431, 500);
 *   -1  — соединение закрыто или клиент ничего не прислал.
 */
int socket_read_request(int client, size_t max_size, int timeout_ms,
                        char **data, size_t *size);

/* Отправить клиенту короткий ответ с кодом code (например, 503). */
void socket_send_status(int client, int code);

/*
 * Закрыть соединение с клиентом. linger = 1 — если запрос мог быть
 * прочитан не полностью: перед закрытием недолго дочитываются остатки,
 * чтобы ядро не оборвало соединение (RST) раньше, чем клиент прочтёт ответ.
 */
void socket_close(int client, int linger);

#endif /* CGI_SOCKET_H */
