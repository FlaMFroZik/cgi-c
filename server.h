/*
 * server.h — HTTP-сервер как библиотека для вашего main.c.
 *
 * Сервер здесь — не отдельная программа и не динамическая библиотека (.so),
 * которую пришлось бы загружать во время работы. Это обычный код, который
 * компонуется с вашей программой на этапе сборки: Makefile собирает его в
 * статическую библиотеку libcgi-server.a, а вы добавляете её в свою
 * программу одной командой:
 *
 *     cc -o myserver main.c libcgi-server.a -pthread
 *
 * Всё, что нужно сделать в main.c:
 *
 *     int cgi_main(char *root, char *data, size_t size, int client)
 *     {
 *         ...обработать запрос, написать ответ в client...
 *     }
 *
 *     int main(int argc, char **argv)
 *     {
 *         return server_run(cgi_main, argc, argv);
 *     }
 *
 * Адрес CGI-функции передаётся в сервер обычным указателем — никаких
 * dlopen()/dlsym(): соответствие типов проверяет компилятор.
 */
#ifndef CGI_SERVER_H
#define CGI_SERVER_H

#include <stddef.h> /* size_t */

/* Размер буфера root: 256 символов, включая завершающий '\0'
 * (то есть сам путь — не длиннее 255 символов). */
#define CGI_ROOT_SIZE 256

/* Значения по умолчанию для ключей командной строки (см. server_run()). */
#define SERVER_DEFAULT_ADDRESS "0.0.0.0" /* -a: все сетевые интерфейсы */
#define SERVER_DEFAULT_PORT    "8080"    /* -p */
#define SERVER_DEFAULT_ROOT    "."       /* -r: текущая папка */
#define SERVER_DEFAULT_THREADS 16        /* -t */
#define SERVER_DEFAULT_MAX     (1024 * 1024) /* -m: макс. размер запроса, байт */
#define SERVER_DEFAULT_TIMEOUT 10        /* -T: таймаут, секунд */
#define SERVER_QUEUE_SIZE      256       /* очередь соединений в пуле потоков */

/*
 * Тип CGI-функции — указатель на функцию вида
 *
 *     int cgi_main(char *root, char *data, size_t size, int client);
 *
 * Имя функции может быть любым: сервер находит её не по имени, а по
 * указателю, который вы передаёте в server_run().
 *
 *   root   — буфер ровно из CGI_ROOT_SIZE (256) символов: абсолютный путь
 *            к корневой папке сервера (ключ -r), всегда завершён '\0'.
 *            У каждого запроса своя копия — её можно менять.
 *   data   — «голые» данные от клиента: байты запроса в точности так, как
 *            они пришли из сокета (строка запроса, заголовки, тело).
 *            Сервер их не разбирает. После последнего байта дописан '\0'.
 *   size   — сколько байт в data (без дописанного '\0').
 *   client — сокет клиента: сюда CGI пишет полный HTTP-ответ.
 *
 * CGI вызывается одновременно из нескольких рабочих потоков, поэтому функция
 * должна быть потокобезопасной (никаких глобальных переменных без мьютекса)
 * и не должна завершать процесс (exit(), abort()).
 *
 * Возвращает HTTP-код отправленного ответа (200, 404, ...) — он попадает
 * в журнал сервера; можно вернуть 0. Отрицательное значение означает
 * «ответ НЕ отправлен» — тогда сервер сам ответит 500 Internal Server Error.
 */
typedef int (*cgi_function_t)(char *root, char *data, size_t size, int client);

/*
 * Запустить сервер с CGI-функцией cgi. Функция блокирующая: возвращается,
 * только когда сервер остановлен (Ctrl+C или SIGTERM), поэтому обычно её
 * результат сразу становится результатом main().
 *
 * argc и argv передавайте как есть — сервер сам разбирает ключи:
 *
 *   -p PORT   порт (по умолчанию 8080)
 *   -a ADDR   адрес для прослушивания (0.0.0.0 — все интерфейсы, :: — IPv6)
 *   -r ROOT   корневая папка, передаётся в CGI как root (по умолчанию ".")
 *   -t N      число рабочих потоков (по умолчанию 16)
 *   -m BYTES  максимальный размер запроса в байтах (по умолчанию 1 МиБ)
 *   -T SEC    таймаут чтения запроса и записи ответа (по умолчанию 10)
 *   -q        не печатать журнал запросов
 *   -h        показать справку (server_run вернёт 0, ничего не запустив)
 *
 * Возвращает 0 при штатной остановке, 1 при ошибке запуска, 2 при неверных
 * ключах — значения подходят в качестве кода выхода вашей программы.
 */
int server_run(cgi_function_t cgi, int argc, char **argv);

/* ======================================================================== */
/* Низкий уровень: функции работы с сокетами                                 */
/*                                                                          */
/* Их использует сам server_run(). Они пригодятся, если захочется написать  */
/* свой цикл обработки запросов вместо готового.                            */
/* ======================================================================== */

/*
 * Открыть слушающий TCP-сокет на address:port (IPv4 или IPv6).
 * Возвращает дескриптор или -1 при ошибке.
 */
int socket_listen(const char *address, const char *port);

/*
 * Прочитать один запрос клиента целиком: заголовки до пустой строки и
 * тело длиной Content-Length. Данные НЕ разбираются и не меняются —
 * это «голые» байты из сокета; после них дописывается '\0'.
 *
 * В *data возвращается буфер (освобождает вызывающий через free(),
 * даже при ошибке), в *size — число байт в нём.
 *
 * Возвращает:
 *    0  — запрос получен полностью;
 *   >0  — HTTP-код ошибки, который надо отправить клиенту
 *         (400, 408, 411, 413, 431, 500);
 *   -1  — соединение закрыто или клиент ничего не прислал.
 */
int socket_read_request(int client, size_t max_size, int timeout_ms,
                        char **data, size_t *size);

/* Отправить клиенту короткий ответ с кодом code (например, 503). */
void socket_send_status(int client, int code);

/*
 * Закрыть соединение с клиентом. linger = 1 — если запрос мог быть
 * прочитан не полностью: перед закрытием недолго дочитываются остатки,
 * чтобы ядро не оборвало соединение (RST) раньше, чем клиент прочтёт ответ.
 */
void socket_close(int client, int linger);

#endif /* CGI_SERVER_H */
