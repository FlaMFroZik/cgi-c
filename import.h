/*
 * import.h — импорт CGI-функции через указатели на функции.
 *
 * CGI здесь — это обычная функция на C, которая обрабатывает один запрос.
 * Её компилируют в динамическую библиотеку (.so), а сервер «импортирует»
 * её во время работы:
 *
 *   1. dlopen()  загружает библиотеку в память процесса;
 *   2. dlsym()   находит в ней функцию по имени (по умолчанию "cgi_main");
 *   3. адрес функции сохраняется в указатель типа cgi_function_t;
 *   4. дальше сервер вызывает CGI только через этот указатель.
 *
 * Этот же заголовок подключает и сама CGI (см. example/main.c), чтобы
 * компилятор проверил: её функция в точности совпадает с типом, который
 * ждёт сервер.
 */
#ifndef CGI_IMPORT_H
#define CGI_IMPORT_H

#include <stddef.h> /* size_t */

/* Размер буфера root: 256 символов, включая завершающий '\0'
 * (то есть сам путь — не длиннее 255 символов). */
#define CGI_ROOT_SIZE 256

/* Имя CGI-функции, которую сервер ищет в библиотеке (меняется ключом -f). */
#define CGI_FUNCTION_NAME "cgi_main"

/*
 * Тип CGI-функции — указатель на функцию вида
 *
 *     int cgi_main(char *root, char *data, size_t size, int client);
 *
 *   root   — буфер ровно из CGI_ROOT_SIZE (256) символов: абсолютный путь
 *            к корневой папке сервера (ключ -r), всегда завершён '\0'.
 *            У каждого запроса своя копия — её можно менять.
 *   data   — «голые» данные от клиента: байты запроса в точности так, как
 *            они пришли из сокета (строка запроса, заголовки, тело).
 *            Сервер их не разбирает. После последнего байта дописан '\0'.
 *   size   — сколько байт в data (без дописанного '\0').
 *   client — сокет клиента: сюда CGI пишет полный HTTP-ответ.
 *
 * Возвращает HTTP-код отправленного ответа (200, 404, ...) — он попадает
 * в журнал сервера; можно вернуть 0. Отрицательное значение означает
 * «ответ НЕ отправлен» — тогда сервер сам ответит 500 Internal Server Error.
 */
typedef int (*cgi_function_t)(char *root, char *data, size_t size, int client);

/* Импортированная CGI: откуда она загружена и указатель на неё. */
typedef struct {
    void          *library;  /* дескриптор библиотеки — результат dlopen() */
    cgi_function_t function; /* указатель на CGI-функцию — результат dlsym() */
} cgi_import_t;

/*
 * Загрузить библиотеку path и импортировать из неё функцию с именем name.
 * Возвращает 0 при успехе и -1 при ошибке (причина печатается в stderr).
 */
int import_library(cgi_import_t *cgi, const char *path, const char *name);

/*
 * Вызвать импортированную CGI-функцию через указатель.
 * root должен указывать на буфер из CGI_ROOT_SIZE символов.
 * Возвращает то же, что вернула CGI-функция (или -1, если CGI не загружена).
 */
int import_call(const cgi_import_t *cgi, char *root, char *data, size_t size, int client);

/*
 * Выгрузить библиотеку (dlclose). Вызывать только тогда, когда ни один
 * поток уже не выполняет код CGI.
 */
void import_close(cgi_import_t *cgi);

#endif /* CGI_IMPORT_H */
